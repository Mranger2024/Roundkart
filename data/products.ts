export const getFeaturedProducts = (): Product[] => products.filter((_, i) => i < 8);
export const getProductBySlug = (slug: string): Product | undefined => products.find((p) => p.slug === slug);
export const getProductsByCategory = (cat: string): Product[] => products.filter((p) => p.category === cat);
export const getRelatedProducts = (currentId: number, category: string): Product[] =>
    products.filter((p) => p.category === category && p.id !== currentId).slice(0, 4);
